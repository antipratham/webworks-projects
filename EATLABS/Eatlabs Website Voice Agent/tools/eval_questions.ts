/**
 * Score retrieval against the question set, and write the answers out.
 *
 *   node tools/eval_questions.ts            # score, print the misses
 *   node tools/eval_questions.ts --write    # also regenerate eval/ANSWERS.md
 *
 * Why this exists: "retrieval feels wrong" is not something you can fix or prove you
 * have fixed. 113 questions with the chunk that ought to answer each one turns it into
 * two numbers, and turns every regression into a named line of output.
 *
 * The questions are hand-written, the way a visitor types them rather than the way the
 * headings are worded. The ANSWERS are not written by hand at all - they are read out
 * of kb.jsonl at run time. That is deliberate: an answer file maintained by hand drifts
 * away from what the agent actually says, and then it is worse than having none.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadIndex, loadChunks } from '../src/retrieve.ts';
import { createEmbedder, probeEmbedder } from '../src/embed.ts';
import { triage } from '../src/triage.ts';

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));
const write = process.argv.includes('--write');

interface Question { q: string; expect: string; topic: string; }

const questions: Question[] = readFileSync(here('../eval/questions.jsonl'), 'utf8')
  .split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l));

const hybrid = process.argv.includes('--hybrid');
const index = loadIndex(here('../kb.jsonl'), hybrid ? here('../kb.vectors.jsonl') : undefined);
const byId = new Map(loadChunks(here('../kb.jsonl')).map((c) => [c.id, c]));

const embedder = hybrid ? createEmbedder() : undefined;
if (hybrid) {
  const probe = await probeEmbedder();
  if (!probe.reachable) {
    console.error(`--hybrid needs an embedding endpoint: ${probe.detail}`);
    process.exit(2);
  }
  console.log(`hybrid: BM25 + ${embedder!.label}, ${index.hasVectors ? 'vectors loaded' : 'NO VECTORS'}\n`);
}

interface Row extends Question { got: string[]; rank: number; }

const rows: Row[] = [];
for (const item of questions) {
  const hits = hybrid
    ? await index.searchHybrid(item.q, 5, embedder)
    : index.search(item.q, 5);
  const got = hits.map((h) => h.chunk.id);
  const at = got.indexOf(item.expect);
  rows.push({ ...item, got, rank: at < 0 ? 0 : at + 1 });
}

const top1 = rows.filter((r) => r.rank === 1).length;
const top3 = rows.filter((r) => r.rank >= 1 && r.rank <= 3).length;
const top5 = rows.filter((r) => r.rank >= 1).length;
const pct = (n: number) => `${((n / rows.length) * 100).toFixed(1)}%`;

console.log(`${rows.length} questions over ${new Set(questions.map((q) => q.expect)).size} chunks\n`);
console.log(`  rank 1       ${String(top1).padStart(3)}  ${pct(top1)}`);
console.log(`  top 3        ${String(top3).padStart(3)}  ${pct(top3)}`);
console.log(`  top 5        ${String(top5).padStart(3)}  ${pct(top5)}`);
console.log(`  not found    ${String(rows.length - top5).padStart(3)}  ${pct(rows.length - top5)}`);

// Per topic, because a single number hides which part of the knowledge base is weak.
const topics = [...new Set(questions.map((q) => q.topic))];
console.log('\nby topic (rank 1):');
for (const topic of topics) {
  const mine = rows.filter((r) => r.topic === topic);
  const hit = mine.filter((r) => r.rank === 1).length;
  const bar = '#'.repeat(Math.round((hit / mine.length) * 20)).padEnd(20, '.');
  console.log(`  ${topic.padEnd(13)} ${bar} ${String(hit).padStart(2)}/${String(mine.length).padEnd(2)}`);
}

const misses = rows.filter((r) => r.rank !== 1);
if (misses.length) {
  console.log(`\n${misses.length} not answered by the intended chunk:\n`);
  for (const m of misses) {
    console.log(`  "${m.q}"`);
    console.log(`     want  ${m.expect}`);
    console.log(`     got   ${m.got[0] ?? '(nothing)'}${m.rank ? `   [intended chunk was rank ${m.rank}]` : '   [not in top 5]'}`);
  }
}

// Triage must not swallow a real question. One misfire here is worse than several
// retrieval misses: the visitor is told to rephrase something they said perfectly well.
const swallowed = questions.filter((item) => triage(item.q).kind !== 'ok');
console.log(`\ntriage: ${swallowed.length} real questions wrongly held back`);
for (const s of swallowed) console.log(`  ${triage(s.q).kind}: "${s.q}"`);

if (write) {
  const lines: string[] = [
    '<!-- GENERATED by tools/eval_questions.ts --write. Do not edit by hand.',
    '     The questions come from eval/questions.jsonl; the answers are read from',
    '     kb.jsonl at generation time, so they are always what the agent would say. -->',
    '',
    '# What the agent answers',
    '',
    `${rows.length} questions a visitor actually asks, and the answer each one gets today.`,
    '',
    'The **Answer** column is the `Spoken:` line of the chunk retrieved — what the voice',
    'agent reads aloud. The text agent gets the fuller version with tables. Nothing here is',
    'written by hand: regenerate it with `node tools/eval_questions.ts --write` after any',
    'knowledge-base change.',
    '',
    `Retrieval reaches the intended chunk first for **${top1} of ${rows.length}** (${pct(top1)}).`,
    'Where it does not, the row is marked and shows what came back instead.',
    '',
  ];
  for (const topic of topics) {
    lines.push(`## ${topic}`, '');
    for (const r of rows.filter((x) => x.topic === topic)) {
      const chunk = byId.get(r.got[0] ?? '');
      const answer = (chunk?.spoken ?? '(nothing retrieved — the agent hands over to a person)')
        .replace(/\s+/g, ' ').trim();
      lines.push(`**${r.q}**`, '', answer, '');
      if (r.rank !== 1) {
        lines.push(`> ⚠ answered from \`${r.got[0] ?? 'nothing'}\`, not the intended \`${r.expect}\`.`, '');
      }
    }
  }
  mkdirSync(here('../eval'), { recursive: true });
  writeFileSync(here('../eval/ANSWERS.md'), lines.join('\n') + '\n', 'utf8');
  console.log(`\nwrote eval/ANSWERS.md (${rows.length} questions)`);
}

process.exit(0);
