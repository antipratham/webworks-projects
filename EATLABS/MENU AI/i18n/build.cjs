/**
 * Builds menu_i18n.json from the per-dish translation tables.
 *
 * The tables are keyed by the dish's base English name, because a "(Half)" portion
 * is the same dish - only the portion word differs, and that is appended per
 * language here rather than translated 40 times.
 *
 *   node i18n/build.cjs
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const menu = JSON.parse(fs.readFileSync(path.join(root, 'menu_database_200items.json'), 'utf8'));

const table = {};
for (const file of ['dishes_1.json', 'dishes_2.json', 'dishes_3.json']) {
  Object.assign(table, JSON.parse(fs.readFileSync(path.join(__dirname, file), 'utf8')));
}

const PORTION = {
  hi: { Half: 'हाफ', Full: 'फुल' },
  kn: { Half: 'ಹಾಫ್', Full: 'ಫುಲ್' },
};

const baseName = (name) => name.replace(/\s*\((Half|Full)\)\s*$/, '').trim();
const portionOf = (name) => (name.match(/\((Half|Full)\)\s*$/) || [])[1] || null;

const out = {};
const missing = new Set();

for (const item of menu.menu) {
  const base = baseName(item.name);
  const entry = table[base];
  if (!entry) {
    missing.add(base);
    continue;
  }
  const portion = portionOf(item.name);
  out[item.id] = {};
  for (const lang of ['hi', 'kn']) {
    const translated = entry[lang];
    if (!translated) continue;
    out[item.id][lang] = {
      name: portion ? `${translated.name} (${PORTION[lang][portion]})` : translated.name,
      description: translated.description,
    };
  }
}

const payload = {
  schema_version: '1.0',
  description:
    'Per-item name and description in Hindi and Kannada, keyed by menu item id. Merged onto the menu at load; any item or language absent here falls back to the English fields. Generated by i18n/build.cjs from the per-dish tables in this folder - edit those, not this file.',
  languages: ['hi', 'kn'],
  items: out,
};

fs.writeFileSync(
  path.join(root, 'menu_i18n.json'),
  JSON.stringify(payload, null, 2) + '\n',
  'utf8',
);

console.log(`translated ${Object.keys(out).length} of ${menu.menu.length} items`);
if (missing.size > 0) {
  console.log(`missing translations for ${missing.size} dish(es):`);
  for (const name of missing) console.log(`  - ${name}`);
  process.exitCode = 1;
}
